export function pageById(id: string) {
  return [...pages, ...additionalPages].find((page) => page.id === id);
}
export function pageAtPath(path: string) {
  return (
    [...pages, ...additionalPages].find((page) => page.href === path) ??
    [...pages, ...additionalPages]
      .sort((a, b) => b.href.length - a.href.length)
      .find((page) => path.startsWith(page.href + "/"))
  );
}
export function groupPages(page: PageDefinition) {
  return page.group
    ? pages.filter((item) => item.hub === page.hub && item.group === page.group)
    : [];
}
