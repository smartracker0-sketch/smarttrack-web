  const [settingsError, setSettingsError] = useState<string | null>(null);

  async function load() {
    setLoading(true);
    try {
      const [alertRes, deviceRes, settingsRes] = await Promise.all([
        fetch("/api/telemetry?type=alerts&unacknowledgedOnly=false"),
        fetch("/api/devices"),
        fetch("/api/telemetry/alert-settings"),
      ]);

      if (alertRes.ok) {
        const data = await alertRes.json();
        const list: AlertRow[] = Array.isArray(data) ? data : data?.content ?? [];
        setAlerts(list.sort((a, b) => new Date(alertTime(b) ?? 0).getTime() - new Date(alertTime(a) ?? 0).getTime()));
      }
      if (deviceRes.ok) {
        const data = await deviceRes.json();
        setDevices(Array.isArray(data) ? data : data?.content ?? []);
      }
      if (settingsRes.ok) {
        const data = await settingsRes.json();
        setSavedSettings(Array.isArray(data) ? data : data?.content ?? []);
      }
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => { load(); }, []);

  const deviceMaps = useMemo(() => deviceLookup(devices), [devices]);
  const periodAlerts = useMemo(() => alerts.filter((alert) => inPeriod(alert, period)), [alerts, period]);
  const knownAlerts = useMemo(() => periodAlerts.filter((alert) => categoryForAlert(alert)), [periodAlerts]);
  const criticalCount = useMemo(() => knownAlerts.filter((alert) => norm(alert.severity) === "CRITICAL").length, [knownAlerts]);
  const nonCriticalCount = Math.max(knownAlerts.length - criticalCount, 0);

  const alertsByCategory = useMemo(() => {
    const grouped = new Map<string, AlertRow[]>();
    ALERT_CATEGORIES.forEach((category) => grouped.set(category.key, []));
    periodAlerts.forEach((alert) => {
      const category = categoryForAlert(alert);
      if (category) grouped.get(category.key)?.push(alert);
    });
    return grouped;
  }, [periodAlerts]);

  const categoryCounts = useMemo(() => {
    const counts = new Map<string, number>();
    ALERT_CATEGORIES.forEach((category) => counts.set(category.key, alertsByCategory.get(category.key)?.length ?? 0));
    return counts;
  }, [alertsByCategory]);

  const selectedCategory = ALERT_CATEGORIES.find((category) => category.key === selectedKey) ?? ALERT_CATEGORIES[0];
  const selectedAlerts = useMemo(() => alertsByCategory.get(selectedCategory.key) ?? [], [alertsByCategory, selectedCategory]);
  const savedSettingsByKey = useMemo(() => {
    const next = new Map<string, SavedSettingRow>();
    savedSettings.forEach((setting) => {
      if (setting.alertKey) next.set(String(setting.alertKey), setting);
    });
    return next;
  }, [savedSettings]);
  const uniqueDevices = useMemo(() => {
    const seen = new Set<string>();
    return devices.filter((device) => {
      const id = String(device.id ?? device.imei ?? "");
      if (!id || seen.has(id)) return false;
      seen.add(id);
      return true;
    });
  }, [devices]);

  const visibleCategories = ALERT_CATEGORIES.filter((category) => {
    const count = categoryCounts.get(category.key) ?? 0;
    const categoryAlerts = alertsByCategory.get(category.key) ?? [];
    const matchesSearch = `${category.title} ${category.description ?? ""}`.toLowerCase().includes(search.toLowerCase());
    const matchesSeverity =
      severityFilter === "All" ||
      (severityFilter === "Critical" && categoryAlerts.some((alert) => norm(alert.severity) === "CRITICAL")) ||
      (severityFilter === "Non Critical" && (count === 0 || categoryAlerts.some((alert) => norm(alert.severity) !== "CRITICAL")));
    return matchesSearch && matchesSeverity;
  });

  const showingFrom = (() => {
    const now = new Date();
    const ms = PERIODS[period].ms;
    if (!ms) return "All available alert history";
    return `${dateText(new Date(now.getTime() - ms).toISOString())} to ${dateText(now.toISOString())}`;
  })();

  async function openSettings(category: AlertCategory) {
    setSettingCategory(category);
    setAlertSettings(DEFAULT_ALERT_SETTINGS);
    setSettingsError(null);
    try {
      const res = await fetch(`/api/telemetry/alert-settings/${encodeURIComponent(category.key)}`, { cache: "no-store" });
      if (res.ok) {
        const saved = await res.json();
        setAlertSettings({
          subUserName: saved.subUserName ?? "all",
          vehicleGroupName: saved.vehicleGroupName ?? "all",
          vehicleIds: Array.isArray(saved.vehicleIds) ? saved.vehicleIds.map(String) : [],
          webNotifications: Boolean(saved.webNotifications),
          sound: Boolean(saved.sound),
          mobileNotifications: Boolean(saved.mobileAppNotifications),
          emailNotifications: Boolean(saved.emailNotifications),
          tripsOnly: Boolean(saved.tripsOnly),
        });
      }
    } catch {
      setSettingsError("Could not load saved alert settings.");
    }
  }

  function updateSettings<K extends keyof AlertSettings>(key: K, value: AlertSettings[K]) {
    setAlertSettings((prev) => ({ ...prev, [key]: value }));
  }

  function toggleVehicle(device: DeviceRow) {
    const id = String(device.id ?? device.imei ?? "");
    if (!id) return;
    setAlertSettings((prev) => ({
      ...prev,
      vehicleIds: prev.vehicleIds.includes(id)
        ? prev.vehicleIds.filter((vehicleId) => vehicleId !== id)
        : [...prev.vehicleIds, id],
    }));
  }

  async function saveSettings() {
    if (!settingCategory) return;
    setSettingsSaving(true);
    setSettingsError(null);
    try {
      const res = await fetch(`/api/telemetry/alert-settings/${encodeURIComponent(settingCategory.key)}`, {
        method: "PUT",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({
          alertTitle: settingCategory.title,
          subUserName: alertSettings.subUserName,
          vehicleGroupName: alertSettings.vehicleGroupName,
          vehicleIds: alertSettings.vehicleIds,
          webNotifications: alertSettings.webNotifications,
          sound: alertSettings.sound,
          mobileAppNotifications: alertSettings.mobileNotifications,
          emailNotifications: alertSettings.emailNotifications,
          tripsOnly: alertSettings.tripsOnly,
        }),
      });
      if (!res.ok) {
        const data = await res.json().catch(() => null);
        throw new Error(data?.message ?? "Could not save alert settings.");
      }
      const saved = await res.json().catch(() => null);
      if (saved?.alertKey) {
        setSavedSettings((prev) => [
          ...prev.filter((setting) => String(setting.alertKey) !== String(saved.alertKey)),
          saved,
        ]);
      }
      setSettingCategory(null);
    } catch (error) {
      setSettingsError(error instanceof Error ? error.message : "Could not save alert settings.");
    } finally {
      setSettingsSaving(false);
    }
  }

