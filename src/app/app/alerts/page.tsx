const PERIODS: Record<PeriodKey, { label: string; ms: number | null }> = {
  "24h": { label: "Last 24 Hours", ms: 24 * 60 * 60 * 1000 },
  "7d": { label: "Last 7 Days", ms: 7 * 24 * 60 * 60 * 1000 },
  "30d": { label: "Last 30 Days", ms: 30 * 24 * 60 * 60 * 1000 },
  all: { label: "All Time", ms: null },
};

const SEVERITY_STYLE: Record<string, string> = {
  CRITICAL: "#EF4444",
  WARNING: "#F59E0B",
  INFO: "#1A7A75",
};

function norm(value?: string | null) {
  return String(value ?? "").trim().toUpperCase();
}

function alertTime(alert: AlertRow) {
  return alert.alertTime ?? alert.eventTime ?? alert.receivedAt ?? alert.createdAt ?? null;
}

function inPeriod(alert: AlertRow, period: PeriodKey) {
  const ms = PERIODS[period].ms;
  if (!ms) return true;
  const value = alertTime(alert);
  if (!value) return false;
  const time = new Date(value).getTime();
  return Number.isFinite(time) && Date.now() - time <= ms;
}

function dateText(value?: string | null) {
  if (!value) return "-";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "-";
  return date.toLocaleString(undefined, {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    hour: "numeric",
    minute: "2-digit",
  });
}

function shortName(value?: string | null) {
  const text = String(value ?? "Vehicle");
  return text.length > 22 ? `${text.slice(0, 18)}...${text.slice(-4)}` : text;
}

function categoryMatches(category: AlertCategory, alert: AlertRow) {
  const type = norm(alert.alertType ?? alert.type);
  return category.alertTypes.includes(type);
}

function categoryForAlert(alert: AlertRow) {
  return ALERT_CATEGORIES.find((category) => categoryMatches(category, alert));
}

function deviceLookup(devices: DeviceRow[]) {
  const byId = new Map<string, DeviceRow>();
  const byImei = new Map<string, DeviceRow>();
  devices.forEach((device) => {
    if (device.id) byId.set(String(device.id), device);
    if (device.imei) byImei.set(String(device.imei), device);
  });
  return { byId, byImei };
}

function vehicleName(alert: AlertRow, devices: ReturnType<typeof deviceLookup>) {
  const device = devices.byId.get(String(alert.deviceId ?? "")) ?? devices.byImei.get(String(alert.deviceImei ?? ""));
  return shortName(alert.vehiclePlate ?? alert.vehicleNumber ?? device?.vehiclePlate ?? device?.name ?? device?.imei ?? alert.deviceImei ?? alert.deviceId);
}

function driverName(alert: AlertRow, devices: ReturnType<typeof deviceLookup>) {
  const device = devices.byId.get(String(alert.deviceId ?? "")) ?? devices.byImei.get(String(alert.deviceImei ?? ""));
  return alert.driverName ?? device?.driverName ?? device?.ownerName ?? "Admin";
}

function deviceOptionLabel(device: DeviceRow) {
  return String(device.vehiclePlate ?? device.name ?? device.imei ?? device.id ?? "Vehicle");
}

function Toggle({
  checked,
  onChange,
  label,
}: {
  checked: boolean;
  onChange: (checked: boolean) => void;
  label: string;
}) {
  return (
    <button
      type="button"
      role="switch"
      aria-checked={checked}
      onClick={() => onChange(!checked)}
      className="flex w-full items-center justify-between gap-4 rounded-lg border border-[#edf2f6] bg-white px-4 py-3 text-left text-sm font-semibold text-[#536987]"
    >
      <span>{label}</span>
      <span
        className="relative h-6 w-11 rounded-full transition"
        style={{ background: checked ? "#23b8c8" : "#d5e2ec" }}
      >
        <span
          className="absolute top-1 h-4 w-4 rounded-full bg-white shadow transition"
          style={{ left: checked ? "23px" : "4px" }}
        />
      </span>
    </button>
  );
}

